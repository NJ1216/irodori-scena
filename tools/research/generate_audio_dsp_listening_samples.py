"""Generate repeatable listening samples from eight existing cast references."""
from __future__ import annotations

import json
import math
import shutil
import wave
from pathlib import Path

import numpy as np

from server.modules.cue_mix import mix_pcm_members
from tools.pcm_analysis import decode_pcm as _decode_pcm, integrated_level as _integrated_level, true_peak as _true_peak
from server.modules.export_service import join_wav_files
from server.modules.overlap_mix import TRUE_PEAK_LIMIT, render_overlap


REPOSITORY = Path(__file__).resolve().parents[2]
SOURCE_PROJECT = REPOSITORY / "userproject" / "異邦の四人と王宮の邂逅.scena"
OUTPUT = REPOSITORY / "artifacts" / "audio-dsp-listening"
SAMPLE_SECONDS = 6.0
OVERLAP_SECONDS = 2.0


README = """# Audio DSP listening samples

This directory is regenerated by `tools/research/generate_audio_dsp_listening_samples.py`.

- `simultaneous/`: 2–8 cast mixes for checking stable perceived level and clipping.
- `overlap/01-sequential-control.wav`: the same two casts without overlap.
- `overlap/02-current-following-cast-priority.wav`: Rust overlap processing. The following cast is preserved, the previous cast is adaptively ducked only as much as the -1 dBTP ceiling requires, and the previous cast exits with a 10 ms ramp.
- `overlap/03-naive-sum-clipped.wav`: untreated comparison.
- `measurements.json`: levels, true peaks, durations, and applied gains.
"""


def level_db(samples: np.ndarray) -> float | None:
    level = _integrated_level(samples)
    return 20 * math.log10(level) if level and level > 0 else None


def details(path: Path) -> dict[str, float | int | None]:
    samples, rate = _decode_pcm(path)
    return {
        "sampleRate": rate,
        "channels": samples.shape[1],
        "durationSeconds": round(len(samples) / rate, 6),
        "integratedLevelDb": round(level_db(samples) or -120.0, 4),
        "truePeakDbtp": round(20 * math.log10(max(_true_peak(samples), 1e-12)), 4),
    }


def trim(source: Path, destination: Path, seconds: float) -> None:
    with wave.open(str(source), "rb") as reader:
        params = reader.getparams()
        frames = reader.readframes(min(reader.getnframes(), round(seconds * reader.getframerate())))
    with wave.open(str(destination), "wb") as writer:
        writer.setparams(params)
        writer.writeframes(frames)


def naive_overlap(previous: Path, following: Path, seconds: float, output: Path) -> None:
    before, rate = _decode_pcm(previous)
    after, following_rate = _decode_pcm(following)
    if rate != following_rate:
        raise ValueError("Sample rates differ")
    frames = min(len(before), len(after), round(seconds * rate))
    combined = np.concatenate((before[:-frames], before[-frames:] + after[:frames], after[frames:]))
    pcm = np.round(np.clip(combined, -1, 32767 / 32768) * 32768).astype("<i2")
    with wave.open(str(output), "wb") as writer:
        writer.setparams((combined.shape[1], 2, rate, 0, "NONE", "not compressed"))
        writer.writeframes(pcm.tobytes())


def generate() -> dict[str, object]:
    sources = sorted((SOURCE_PROJECT / "media" / "characters").glob("*/reference.wav"))
    if len(sources) != 8:
        raise RuntimeError(f"Expected eight 48 kHz cast references, found {len(sources)}")
    shutil.rmtree(OUTPUT, ignore_errors=True)
    inputs = OUTPUT / "inputs"
    simultaneous = OUTPUT / "simultaneous"
    overlap = OUTPUT / "overlap"
    for directory in (inputs, simultaneous, overlap):
        directory.mkdir(parents=True)
    trimmed = []
    for index, source in enumerate(sources, 1):
        destination = inputs / f"cast-{index}.wav"
        trim(source, destination, SAMPLE_SECONDS)
        trimmed.append(destination)

    report: dict[str, object] = {
        "calculation": "numpy float32 accumulation; PCM16 output",
        "truePeakLimitDbtp": round(20 * math.log10(TRUE_PEAK_LIMIT), 4),
        "inputs": {path.name: details(path) for path in trimmed},
    }
    reference_level = max(float(details(path)["integratedLevelDb"] or -120) for path in trimmed)
    mixes = {}
    for count in range(2, 9):
        output = simultaneous / f"simultaneous-{count}-casts.wav"
        mix_pcm_members([(path, 0.0) for path in trimmed[:count]], output)
        measurement = details(output)
        measurement["differenceFromLoudestInputDb"] = round(
            float(measurement["integratedLevelDb"] or -120) - reference_level, 4
        )
        mixes[str(count)] = measurement
    report["simultaneous"] = mixes

    # This fixed pair leaves measurable headroom for the production adaptive-ducking rule.
    first, second = trimmed[6], trimmed[2]
    sequential = overlap / "01-sequential-control.wav"
    join_wav_files([(first, 0.25), (second, 0)], sequential)
    cache = overlap / "overlap-cache.wav"
    gains = render_overlap(first, second, OVERLAP_SECONDS, cache)
    protected = overlap / "02-current-following-cast-priority.wav"
    join_wav_files([(first, -OVERLAP_SECONDS), (second, 0)], protected, overlap_files=[cache, None])
    naive = overlap / "03-naive-sum-clipped.wav"
    naive_overlap(first, second, OVERLAP_SECONDS, naive)
    report["overlap"] = {
        "previousInput": first.name,
        "followingInput": second.name,
        "requestedSeconds": OVERLAP_SECONDS,
        "previousGain": round(gains["previousGain"], 6),
        "followingGain": round(gains["followingGain"], 6),
        "sequentialControl": details(sequential),
        "currentFollowingCastPriority": details(protected),
        "naiveSumClipped": details(naive),
    }
    (OUTPUT / "measurements.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    (OUTPUT / "README.md").write_text(README)
    return report


if __name__ == "__main__":
    print(json.dumps(generate(), ensure_ascii=False, indent=2))
