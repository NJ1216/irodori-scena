import type { DialogueLine, StudioProject, Take } from "../../types";
import { selectedTake } from "../shared/studio-utils";

export const autoGenerationEndedWithoutTake = "自動生成が終了しましたが、この行は未生成です。";

type WaitForTakeOptions = {
  line: DialogueLine;
  projectRef: { current: StudioProject | null };
  busyRef: { current: string | null };
  waiters: { current: Set<() => void> };
  wasStopped: () => boolean;
  isGenerationActive?: () => boolean;
  setNotice: (notice: string) => void;
};

export function wakeContinuousPlaybackWaiters(waiters: { current: Set<() => void> }) {
  for (const wake of waiters.current) wake();
  waiters.current.clear();
}

function selectedTakeForLine(project: StudioProject | null, lineId: string) {
  const line = project?.scenes.flatMap((scene) => scene.lines).find((item) => item.id === lineId);
  return line ? selectedTake(line) : undefined;
}

export async function waitForAutoGeneratedTake({ line, projectRef, busyRef, waiters, wasStopped, isGenerationActive, setNotice }: WaitForTakeOptions): Promise<Take | undefined> {
  while (!wasStopped()) {
    const take = selectedTakeForLine(projectRef.current, line.id);
    if (take) return take;
    if (busyRef.current !== "export" && !isGenerationActive?.()) {
      throw new Error(autoGenerationEndedWithoutTake);
    }
    setNotice(`次の行の音声を待っています…「${line.text.slice(0, 20)}${line.text.length > 20 ? "…" : ""}」`);
    await new Promise<void>((resolve) => {
      let timeout = 0;
      const finish = () => {
        window.clearTimeout(timeout);
        waiters.current.delete(wake);
        resolve();
      };
      timeout = window.setTimeout(finish, 250);
      const wake = () => finish();
      waiters.current.add(wake);
    });
  }
  return undefined;
}
