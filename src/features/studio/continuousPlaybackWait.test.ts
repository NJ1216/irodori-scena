import { describe, expect, it, vi } from "vitest";
import type { DialogueLine, StudioProject, Take } from "../../types";
import { autoGenerationEndedWithoutTake, waitForAutoGeneratedTake, wakeContinuousPlaybackWaiters } from "./continuousPlaybackWait";

const line = (take?: Take): DialogueLine => ({
  id: "line-1",
  characterId: "cast-1",
  text: "次の台詞です",
  stageDirection: "",
  takes: take ? [take] : [],
  selectedTakeId: take?.id ?? null,
});

const take: Take = {
  id: "take-1",
  audioUrl: "/audio/take-1.wav",
  seed: 1,
  quality: "fast",
  stageDirection: "",
  createdAt: 1,
};

const projectWith = (nextLine: DialogueLine) => ({ scenes: [{ id: "scene-1", title: "Scene 1", lines: [nextLine] }] }) as StudioProject;

describe("continuous playback generation wait", () => {
  it("resumes when the selected take arrives", async () => {
    const projectRef = { current: projectWith(line()) };
    const waiters = { current: new Set<() => void>() };
    const result = waitForAutoGeneratedTake({
      line: line(),
      projectRef,
      busyRef: { current: "export" },
      waiters,
      wasStopped: () => false,
      setNotice: vi.fn(),
    });
    await vi.waitFor(() => expect(waiters.current.size).toBe(1));
    projectRef.current = projectWith(line(take));
    wakeContinuousPlaybackWaiters(waiters);
    await expect(result).resolves.toEqual(take);
  });

  it("stops rather than skipping when auto generation finishes without a take", async () => {
    const waiters = { current: new Set<() => void>() };
    const busyRef = { current: "export" as string | null };
    const result = waitForAutoGeneratedTake({
      line: line(),
      projectRef: { current: projectWith(line()) },
      busyRef,
      waiters,
      wasStopped: () => false,
      setNotice: vi.fn(),
    });
    await vi.waitFor(() => expect(waiters.current.size).toBe(1));
    busyRef.current = null;
    wakeContinuousPlaybackWaiters(waiters);
    await expect(result).rejects.toThrow(autoGenerationEndedWithoutTake);
  });

  it("waits for the ordinary auto-generation queue too", async () => {
    const projectRef = { current: projectWith(line()) };
    const waiters = { current: new Set<() => void>() };
    const result = waitForAutoGeneratedTake({
      line: line(),
      projectRef,
      busyRef: { current: null },
      waiters,
      wasStopped: () => false,
      isGenerationActive: () => true,
      setNotice: vi.fn(),
    });
    await vi.waitFor(() => expect(waiters.current.size).toBe(1));
    projectRef.current = projectWith(line(take));
    wakeContinuousPlaybackWaiters(waiters);
    await expect(result).resolves.toEqual(take);
  });
});
